# Generate documentation tokens from the same CSV used by R rendering.
# Keep this in the shared theme; do not duplicate token values across packages.
cttir_write_integration <- function(root=".") {
  out<-base::file.path(root,"integration")
  base::dir.create(out,recursive=TRUE,showWarnings=FALSE)
  block<-function(mode,selector) c(base::paste0(selector," {"),
    base::sprintf("  --cttir-%s: %s;",c("page","text","heading","link","code-surface","border"),
      base::vapply(c("page","text","heading","link","code_surface","border"),
        function(x)cttir_token(mode,x),character(1))),
    base::paste0("  --cttir-show-light: ",if(mode=="light")"block" else "none",";"),
    base::paste0("  --cttir-show-dark: ",if(mode=="dark")"block" else "none",";"),"}")
  lines<-c("/* Generated by write_integration.R from design_tokens.csv. */",
    ":root {",base::sprintf('  --cttir-font-body: "%s", system-ui, sans-serif;',cttir_token("type","body_font")),
    base::sprintf('  --cttir-font-code: "%s", ui-monospace, monospace;',cttir_token("type","code_font")),
    base::sprintf('  --cttir-font-brand: "%s", ui-monospace, monospace;',cttir_token("type","brand_font")),
    base::paste0("  --cttir-brand-weight: ",cttir_token("type","brand_weight"),";"),"}",
    block("light",":root"),"@media (prefers-color-scheme: dark) {",block("dark",":root"),"}",
    block("light",'[data-bs-theme="light"], body.colorscheme-light'),
    block("dark",'[data-bs-theme="dark"], body.colorscheme-dark'),
    "@media (prefers-color-scheme: dark) {",block("dark","body.colorscheme-auto"),"}")
  for(f in base::names(cttir_accents)) lines<-c(lines,
    base::sprintf('[data-cttir-topic="%s"] { --cttir-topic: %s; }',f,cttir_accents[[f]]))
  base::writeLines(lines,base::file.path(out,"cttir-tokens.css"))
  # Local font files make the standalone demonstration work without a CDN.
  base::dir.create(base::file.path(out,"fonts"),showWarnings=FALSE)
  font_files<-c("Inter-static.ttf","InterBold-static.ttf","OFL.txt",
    "JetBrainsMono-Regular.ttf","JetBrainsMono-SemiBold.ttf","JetBrainsMono-OFL.txt")
  base::file.copy(base::file.path(root,"fonts",font_files),base::file.path(out,"fonts"),overwrite=TRUE)
  base::invisible(out)
}
