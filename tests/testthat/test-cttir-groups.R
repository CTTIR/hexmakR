test_that("native and fresh parts receive readable names and default groups", {
  d <- hex_design("phenoscapR")
  layers <- hex_layers(d)
  expect_equal(hex_groups(d)$frame$label, "Frame")
  expect_equal(hex_groups(d)$name$label, "Name")
  expect_equal(hex_groups(d)$icon$members, layers$id[layers$role == "motif"])
  expect_true(all(nzchar(layers$name)))
  expect_false(any(grepl("^layer_", layers$name)))
  fresh <- hex_add_part(logo_design("Study"), "circle")
  fresh <- hex_add_part(fresh, "circle")
  expect_equal(tail(hex_layers(fresh)$name, 2), c("Circle 1", "Circle 2"))
  expect_equal(hex_groups(fresh)$icon$members, c("part_0001", "part_0002"))
})

test_that("names and custom groups retain appearance and roundtrip", {
  skip_without_cairo()
  d <- hex_add_part(logo_design("Study"), "circle")
  d <- hex_add_part(d, "rectangle")
  before <- tempfile(fileext = ".png")
  after <- tempfile(fileext = ".png")
  project <- tempfile(fileext = ".json")
  on.exit(unlink(c(before, after, project)))
  hex_export(d, before, width = 160)
  named <- hex_label_layer(d, "part_0001", "Cell")
  named <- hex_group_layers(named, c("part_0001", "part_0002"), "Package icon")
  expect_equal(hex_layers(named)$name[3], "Cell")
  groups <- hex_groups(named)
  custom <- tail(names(groups), 1)
  expect_equal(groups[[custom]]$label, "Package icon")
  expect_equal(groups[[custom]]$members, c("part_0001", "part_0002"))
  expect_false("icon" %in% names(groups))
  named <- hex_rename_group(named, custom, "Cells")
  hex_export(named, after, width = 160)
  expect_equal(png::readPNG(before), png::readPNG(after))
  hex_save_design(named, project)
  restored <- hex_read_design(project)
  expect_equal(restored$labels, named$labels)
  expect_equal(restored$groups, named$groups)
  expect_equal(hex_layers(restored)$name, hex_layers(named)$name)
  single <- hex_group_layers(named, "part_0001", "One cell", group = custom)
  hex_save_design(single, project)
  expect_equal(hex_read_design(project)$groups, single$groups)
})

test_that("group membership is exclusive and explicit ungrouping persists", {
  d <- hex_add_part(logo_design("Study"), "circle")
  d <- hex_add_part(d, "rectangle")
  grouped <- hex_group_layers(d, "part_0001", "Cell")
  members <- unlist(lapply(hex_groups(grouped), `[[`, "members"))
  expect_false(anyDuplicated(unname(members)) > 0)
  expect_equal(hex_groups(grouped)$icon$members, "part_0002")
  ungrouped <- hex_ungroup_layers(grouped, hex_layers(grouped)$id)
  expect_identical(hex_groups(ungrouped), list())
  path <- tempfile(fileext = ".json")
  on.exit(unlink(path))
  hex_save_design(ungrouped, path)
  expect_identical(hex_groups(hex_read_design(path)), list())
  named <- hex_label_layer(grouped, "part_0001", "Cell")
  removed <- hex_remove_part(named, "part_0001")
  expect_null(removed$labels$part_0001)
  expect_false("part_0001" %in% unlist(lapply(hex_groups(removed), `[[`, "members")))
  expect_silent(hex_grob(removed))
})

test_that("invalid metadata cannot introduce dangling or duplicate items", {
  d <- logo_design("Study")
  expect_error(hex_label_layer(d, "part_9999", "Absent"), "Unknown")
  expect_error(hex_label_layer(d, "layer_0001", "two\nlines"), "single-line")
  expect_error(hex_label_layer(d, "layer_0001", strrep("x", 81)), "short")
  expect_error(hex_group_layers(d, "part_9999"), "existing")
  expect_error(hex_group_layers(d, "layer_0001", group = "absent"), "Unknown")
  bad <- d
  bad$groups <- list(group_0001 = list(label = "One", members = "layer_0001"),
                     group_0002 = list(label = "Two", members = "layer_0001"))
  expect_error(hex_grob(bad), "only one")
  bad$groups <- list(group_0001 = list(label = "Missing", members = "part_9999"))
  expect_error(hex_grob(bad), "missing")
  bad$groups <- list(group_0001 = list(label = "Wrong", members = list(a = "layer_0001")))
  expect_error(hex_grob(bad), "members")
})
