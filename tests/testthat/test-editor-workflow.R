test_that("new parts can be edited duplicated removed and restored", {
  shiny::testServer(.cttir_editor_server, {
    session$setInputs(label = "My study", shape = "square", mode = "light",
      layout = "lockup", generic_icon = "blank", apply_design = 1)
    expect_identical(current()$label, "My study")
    expect_identical(current()$shape, "square")
    session$setInputs(part_type = "circle", add_part = 1)
    id <- tail(hex_layers(current())$id, 1)
    expect_match(id, "^part_")
    session$setInputs(layer = id, fill = "#E03030", stroke = "#112233",
      dx = .1, dy = -.05, scale = 1.3, lwd = 2, alpha = .75, visible = TRUE,
      coords_x = "", coords_y = "", apply_layer = 1)
    expect_null(error())
    expect_equal(current()$layers[[id]]$fill, "#E03030")
    expect_equal(current()$layers[[id]]$dx, .1)
    edited <- current()
    session$setInputs(duplicate_part = 1)
    copied <- tail(hex_layers(current())$id, 1)
    expect_false(identical(copied, id))
    expect_equal(.layer_leaf(hex_grob(current())$children[[copied]])$gp$fill,
      .layer_leaf(hex_grob(edited)$children[[id]])$gp$fill)
    duplicated <- current()
    session$setInputs(layer = copied, remove_part = 1)
    expect_false(copied %in% hex_layers(current())$id)
    expect_true(id %in% hex_layers(current())$id)
    session$setInputs(undo = 1)
    expect_identical(current(), duplicated)
    session$setInputs(shape = "pentagon", apply_design = 2)
    expect_identical(current()$parts, duplicated$parts)
    expect_equal(current()$layers[[id]], duplicated$layers[[id]])
    expect_null(error())
  })
})

test_that("archive parts and artwork preserve the recipient logo", {
  shiny::testServer(.cttir_editor_server, {
    session$setInputs(label = "Recipient", shape = "pentagon",
      generic_icon = "blank", apply_design = 1)
    session$setInputs(role = "face", role_color = "#183C32", apply_color = 1)
    session$setInputs(part_type = "rectangle", add_part = 1)
    before <- current()
    source <- hex_design("phenoscapR")
    part <- hex_layers(source)$id[hex_layers(source)$role == "motif"][[1]]
    session$setInputs(identity = "phenoscapR", archive_layer = part)
    expect_identical(current(), before)
    session$setInputs(archive_add_part = 1)
    expect_identical(current()$label, before$label)
    expect_identical(current()$shape, before$shape)
    expect_identical(current()$colors, before$colors)
    expect_identical(current()$parts[names(before$parts)], before$parts)
    expect_length(current()$parts, length(before$parts) + 1L)
    one <- current()
    session$setInputs(archive_add_motif = 1)
    expect_gt(length(current()$parts), length(one$parts))
    expect_identical(current()$label, before$label)
    expect_identical(current()$shape, before$shape)
    expect_identical(current()$colors, before$colors)
    assembled <- current()
    old_baseline <- baseline()
    session$setInputs(archive_load = 1)
    expect_identical(current()$label, "phenoscapR")
    expect_true(current()$archive)
    expect_identical(baseline(), current())
    session$setInputs(undo = 1)
    expect_identical(current(), assembled)
    expect_identical(baseline(), old_baseline)
    expect_null(error())
  })
})

test_that("opening and resetting projects keep predictable undo boundaries", {
  shiny::testServer(.cttir_editor_server, {
    session$flushReact()
    initial <- current()
    session$setInputs(part_type = "line", add_part = 1)
    assembled <- current()
    session$setInputs(new_project = 1)
    expect_identical(current(), initial)
    session$setInputs(undo = 1)
    expect_identical(current(), assembled)
    expect_identical(baseline(), initial)
    imported <- hex_add_part(logo_design("Imported", shape = "square"), "circle")
    path <- tempfile(fileext = ".json")
    on.exit(unlink(path), add = TRUE)
    hex_save_design(imported, path)
    session$setInputs(project = data.frame(datapath = path))
    expect_equal(current(), imported)
    expect_equal(baseline(), imported)
    session$setInputs(undo = 2)
    expect_identical(current(), assembled)
    expect_identical(baseline(), initial)
    session$setInputs(reset = 1)
    expect_identical(current(), initial)
    expect_null(error())
  })
})

test_that("an empty unframed canvas remains usable after deleting its last part", {
  shiny::testServer(.cttir_editor_server, {
    session$setInputs(layout = "motif", label = "", generic_icon = "blank",
      apply_design = 1)
    expect_equal(nrow(hex_layers(current())), 0)
    session$setInputs(part_type = "circle", add_part = 1)
    id <- tail(hex_layers(current())$id, 1)
    session$setInputs(layer = id, remove_part = 1)
    expect_equal(nrow(hex_layers(current())), 0)
    expect_null(selection())
    expect_null(error())
    session$setInputs(undo = 1)
    expect_true(id %in% hex_layers(current())$id)
  })
})

test_that("renaming edited glyphs keeps styling and discards obsolete points", {
  shiny::testServer(.cttir_editor_server, {
    session$flushReact()
    parts <- hex_layers(current())
    id <- parts$id[parts$role == "name"][[1]]
    g <- .layer_leaf(hex_grob(current())$children[[id]])
    session$setInputs(layer = id, fill = "#FFFF00", stroke = "", dx = .02,
      dy = 0, scale = 1, lwd = 1, alpha = 1, visible = TRUE,
      coords_x = paste(as.numeric(g$x), collapse = ","),
      coords_y = paste(as.numeric(g$y), collapse = ","), apply_layer = 1)
    expect_null(error())
    session$setInputs(label = "X", generic_icon = "keep", apply_design = 1)
    expect_identical(current()$label, "X")
    expect_equal(current()$layers[[id]]$fill, "#FFFF00")
    expect_equal(current()$layers[[id]]$dx, .02)
    expect_null(current()$layers[[id]]$x)
    expect_null(current()$layers[[id]]$y)
    expect_null(error())
  })
})
